// ==============================
// MULTI PAGE PDF EXPORT
// ==============================

async function exportMultiPagePDF(
  pages,
  filename
) {

  const { jsPDF } = window.jspdf;

  const pdf = new jsPDF(
    "p",
    "mm",
    "a4"
  );

  for (let i = 0; i < pages.length; i++) {

    const page = pages[i];

    const canvas =
      await html2canvas(page, {

        scale: 2,

        useCORS: true
      });

    const imgData =
      canvas.toDataURL("image/png");

    const pdfWidth = 210;

    const pdfHeight =
      (canvas.height * pdfWidth) /
      canvas.width;

    if (i > 0) {

      pdf.addPage();
    }

    pdf.addImage(
      imgData,
      "PNG",
      0,
      0,
      pdfWidth,
      pdfHeight
    );
  }

  // CLEANUP MEMORY
  document.getElementById(
    "pdfRoot"
  ).innerHTML = "";

  pdf.save(filename);
}

